# Light Controls

# This code will handle the light controls in the system.

def turn_on_light(light_id):
    """Turns on the specified light."""
    print(f"Light {light_id} turned on.")

def turn_off_light(light_id):
    """Turns off the specified light."""
    print(f"Light {light_id} turned off.")

# Example usage
turn_on_light(1)
turn_off_light(1)
